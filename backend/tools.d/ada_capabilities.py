_FALLBACK_GROUP = "misc"
_LAYER_PRIORITY = {"builtin": 0, "dropin": 1, "guest": 2}

_ERR_NOT_GENERATED = "capability list not generated — run the catalog producer"


def _snapshot_path() -> Path:
    return Path(os.environ.get("ADA_TOOLS_SNAPSHOT") or _DEFAULT_SNAPSHOT)


# mtime-keyed cache — same pattern as tool_runner/common.py::_tool_guide,
# but keyed on (path, mtime_ns) so a deploy-time file swap is picked up
# without a restart. Value is (data, error).
_SNAPSHOT_CACHE: tuple[str, tuple[dict[str, Any] | None, str | None]] | None = None


def _read_snapshot(path: Path) -> tuple[dict[str, Any] | None, str | None]:
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None, _ERR_NOT_GENERATED
    if not isinstance(raw, dict) or not isinstance(raw.get("tools"), list):
        return None, _ERR_NOT_GENERATED
    try:
        major = int(raw.get("schema"))
    except (TypeError, ValueError):
        major = None
    if major != _SCHEMA:
        return None, (
            f"capability snapshot schema {raw.get('schema')!r} unsupported "
            f"— consumer expects schema {_SCHEMA}")
    return raw, None


def _snapshot() -> tuple[dict[str, Any] | None, str | None]:
    global _SNAPSHOT_CACHE
    path = _snapshot_path()
    try:
        mtime_ns = path.stat().st_mtime_ns
    except OSError:
        return None, _ERR_NOT_GENERATED
    key = f"{path}#{mtime_ns}"
    if _SNAPSHOT_CACHE is not None and _SNAPSHOT_CACHE[0] == key:
        return _SNAPSHOT_CACHE[1]
    result = _read_snapshot(path)
    _SNAPSHOT_CACHE = (key, result)
    return result


def _canonical_tools(snap: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """name -> preferred tools[] row. Drops absorbed _ALIASES names
    (never surface) and dedupes multi-layer rows (builtin > dropin >
    guest) so a name counts once."""
    aliases = snap.get("aliases")
    absorbed = {str(k) for k in aliases} if isinstance(aliases, dict) else set()
    out: dict[str, dict[str, Any]] = {}
    for row in snap.get("tools") or []:
        if not isinstance(row, dict):
            continue
        name = str(row.get("name") or "")
        if not name or name in absorbed:
            continue
        prev = out.get(name)
        if prev is None or _LAYER_PRIORITY.get(
                str(row.get("layer") or ""), 9) < _LAYER_PRIORITY.get(
                str(prev.get("layer") or ""), 9):
            out[name] = row
    return out


def _group_label(name: str, row: dict[str, Any]) -> str:
    fam = str(row.get("family") or "")
    for label, families, names, prefixes in _GROUPS:
        if fam in families or name in names or any(
                name.startswith(p) for p in prefixes):
            return label
    return _FALLBACK_GROUP


def _groups(canon: dict[str, dict[str, Any]]) -> list[dict[str, Any]]:
    by_label: dict[str, list[str]] = {}
    for name, row in canon.items():
        by_label.setdefault(_group_label(name, row), []).append(name)
    order = [g[0] for g in _GROUPS] + [_FALLBACK_GROUP]
    return [
        {"label": label, "tools": sorted(by_label[label])}
        for label in order if by_label.get(label)
    ]


def _stale_note(snap: dict[str, Any]) -> str | None:
    """Drift caveat per contract — echoed snapshot fields only (the
    answer stays byte-deterministic for an identical snapshot)."""
    src = snap.get("source") or {}
    reasons: list[str] = []
    try:
        behind = int(str(src.get("behind") or "0"))
    except (TypeError, ValueError):
        behind = 0
    if behind > 0:
        reasons.append(f"{behind} commit(s) behind the ada-voice checkout")
    generated = snap.get("generated_at")
    if generated:
        try:
            dt = datetime.fromisoformat(str(generated).replace("Z", "+00:00"))
            if dt.tzinfo is None:
                dt = dt.replace(tzinfo=timezone.utc)
            age = (datetime.now(timezone.utc) - dt).days
            if age > _MAX_SNAPSHOT_AGE_DAYS:
                reasons.append(f"generated {age} days ago")
        except ValueError:
            pass
    return "; ".join(reasons) or None


def _source_meta(snap: dict[str, Any]) -> dict[str, Any]:
    src = snap.get("source") or {}
    return {
        "generated_at": snap.get("generated_at"),
        "head": src.get("head"),
        "head_date": src.get("head_date"),
        "behind": src.get("behind"),
        "stale": _stale_note(snap) is not None,
    }


def _overview(snap: dict[str, Any], canon: dict[str, dict[str, Any]],
              groups: list[dict[str, Any]]) -> dict[str, Any]:
    src = snap.get("source") or {}
    head_date = str(src.get("head_date") or "unknown")
    total = len(canon)
    core = sum(1 for r in canon.values() if r.get("layer") == "builtin")
    addon = total - core
    lines = [
        f"I have {total} capabilities — {core} core + {addon} add-on "
        f"tools — as of {head_date}."
    ]
    stale = _stale_note(snap)
    if stale:
        lines.append(f"Note: the snapshot may be stale — {stale}.")
    for g in groups:
        names = g["tools"]
        shown = ", ".join(names[:_NAMES_PER_GROUP])
        extra = len(names) - _NAMES_PER_GROUP
        if extra > 0:
            shown += f" …+{extra} more"
        lines.append(f"- {g['label']} ({len(names)}): {shown}")
    lines.append("Ask me about a specific tool or area for details.")
    return {
        "ok": True,
        "mode": "overview",
        "answer": "\n".join(lines),
        "counts": {"total": total, "core": core, "addon": addon},
        "groups": groups,
        "snapshot": _source_meta(snap),
    }


def _trigger_lines(row: dict[str, Any]) -> list[str]:
    trig = [
        " ".join(str(t).split())[:_MAX_TRIGGER_CHARS]
        for t in (row.get("triggers") or [])[:_MAX_TRIGGERS_SHOWN]
        if str(t or "").strip()
    ]
    return trig


def _tool_detail(canon: dict[str, dict[str, Any]], name: str,
                 snap: dict[str, Any],
                 alias_note: str = "") -> dict[str, Any]:
    row = canon[name]
    purpose = str(row.get("purpose") or "").strip() or "no description"
    policy = str(row.get("policy") or "").strip() or "read"
    meta = [f"policy {policy}"]
    if row.get("backend"):
        meta.append(f"backend {row['backend']}")
    if row.get("timeout_s") is not None:
        meta.append(f"timeout {row['timeout_s']}s")
    if row.get("secondary"):
        meta.append("secondary-ok")
    fam = str(row.get("family") or "").strip()
    if fam:
        meta.append(f"family {fam}")
    if row.get("last_changed"):
        meta.append(f"last changed {row['last_changed']}")
    lines = [f"{alias_note}{name} — {purpose}", " · ".join(meta)]
    trig = _trigger_lines(row)
    if trig:
        lines.append("People ask things like: " + " / ".join(
            f'"{t}"' for t in trig))
    else:
        lines.append("No recorded trigger phrases yet.")
    return {
        "ok": True,
        "mode": "detail",
        "kind": "tool",
        "tool": name,
        "answer": "\n".join(lines),
        "tool_info": {
            k: row.get(k) for k in (
                "name", "layer", "purpose", "description", "backend",
                "registry", "policy", "timeout_s", "secondary", "schema",
                "guide", "triggers", "last_changed", "family",
                "source_file")
        },
        "snapshot": _source_meta(snap),
    }


def _family_detail(snap: dict[str, Any], canon: dict[str, dict[str, Any]],
                   fname: str) -> dict[str, Any]:
    spec = (snap.get("families") or {}).get(fname) or {}
    members = sorted(
        n for n, r in canon.items()
        if str(r.get("family") or "") == fname)
    canonical = str(spec.get("canonical") or "")
    status = str(spec.get("status") or "unknown")
    lines = [
        f"{fname} — merge family ({status}); canonical tool: "
        f"{canonical or 'unknown'}."
    ]
    for n in members:
        purpose = str(canon[n].get("purpose") or "").strip()
        lines.append(f"- {n}: {purpose or 'no description'}")
    absorbed = [str(a) for a in (spec.get("absorbed") or [])]
    if absorbed:
        lines.append(
            "Old names that still route here: " + ", ".join(absorbed))
    return {
        "ok": True,
        "mode": "detail",
        "kind": "family",
        "family": fname,
        "answer": "\n".join(lines),
        "family_info": {
            "canonical": canonical,
            "status": status,
            "absorbed": absorbed,
            "merge_card": spec.get("merge_card"),
            "scenario": spec.get("scenario"),
            "members": members,
        },
        "snapshot": _source_meta(snap),
    }


def _group_detail(canon: dict[str, dict[str, Any]],
                  group: dict[str, Any],
                  snap: dict[str, Any]) -> dict[str, Any]:
    lines = [f"{group['label']} — {len(group['tools'])} tools:"]
    for n in group["tools"]:
        purpose = str(canon[n].get("purpose") or "").strip()
        lines.append(f"- {n}: {purpose or 'no description'}")
    return {
        "ok": True,
        "mode": "detail",
        "kind": "group",
        "group": group["label"],
        "answer": "\n".join(lines),
        "snapshot": _source_meta(snap),
    }


def _detail(snap: dict[str, Any], canon: dict[str, dict[str, Any]],
            groups: list[dict[str, Any]], topic: str) -> dict[str, Any]:
    tn = " ".join(topic.split()).lower()
    names = sorted(canon)
    # 1. exact canonical tool name
    for n in names:
        if n.lower() == tn:
            return _tool_detail(canon, n, snap)
    # 2. absorbed alias name — redirect to the canonical seat (old names
    #    route, they are just never listed as surface)
    aliases = snap.get("aliases")
    if isinstance(aliases, dict):
        for old, new in aliases.items():
            if str(old).lower() == tn:
                target = str(new)
                if target in canon:
                    return _tool_detail(
                        canon, target, snap,
                        alias_note=f"'{old}' is an old name — it routes "
                                   f"to {target}.\n")
                return {
                    "ok": True, "mode": "detail", "kind": "alias",
                    "answer": (f"'{old}' is an absorbed name — it routes "
                               f"to '{target}', which has no row in this "
                               "snapshot."),
                    "snapshot": _source_meta(snap),
                }
    # 3. area/group label (substring either direction)
    for g in groups:
        gl = g["label"].lower()
        if tn == gl or tn in gl or gl in tn:
            return _group_detail(canon, g, snap)
    # 4. merge-family key
    families = snap.get("families") or {}
    for fname in sorted(families):
        if str(fname).lower() == tn:
            return _family_detail(snap, canon, str(fname))
    # 5. unique substring match on tool names
    matches = [n for n in names if tn in n.lower()]
    if len(matches) == 1:
        return _tool_detail(canon, matches[0], snap)
    if matches:
        lines = [f"'{topic}' matches {len(matches)} tools:"]
        for n in matches:
            purpose = str(canon[n].get("purpose") or "").strip()
            lines.append(f"- {n}: {purpose or 'no description'}")
        lines.append("Ask about one of them by exact name for detail.")
        return {
            "ok": True, "mode": "detail", "kind": "matches",
            "answer": "\n".join(lines),
            "matches": matches,
            "snapshot": _source_meta(snap),
        }
    return {
        "ok": False,
        "error": f"no capability, tool, family, or area named {topic!r}",
        "hint": "omit topic for the grouped overview, or use a tool name "
                "like 'home_search' or an area like 'home control'",
    }


async def run(runner: Any, **args: Any) -> dict[str, Any]:
    topic = str(args.get("topic") or "").strip()
    try:
        snap, err = _snapshot()
    except Exception as exc:  # never raise into the model
        logger.warning("ada_capabilities snapshot load failed: %s", exc)
        return {"ok": False, "error": _ERR_NOT_GENERATED}
    if snap is None:
        logger.warning("ada_capabilities: %s", err)
        return {"ok": False, "error": err or _ERR_NOT_GENERATED}
    stale = _stale_note(snap)
    if stale:
        logger.warning("ada_capabilities: snapshot drift — %s", stale)
    try:
        canon = _canonical_tools(snap)
        groups = _groups(canon)
        if not canon:
            return {"ok": False, "error": _ERR_NOT_GENERATED}
        if topic:
            return _detail(snap, canon, groups, topic)
        return _overview(snap, canon, groups)
    except Exception as exc:
        logger.warning("ada_capabilities answer build failed: %s", exc)
        return {"ok": False, "error": _ERR_NOT_GENERATED}
