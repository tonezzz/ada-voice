"""ada_capabilities — the "what can you do" read path.

Card ada-capabilities-verb-wiring; contract: chaba
docs/kb/ada-tools-verb-contract.md (producer/consumer split — the
snapshot is generated by chaba's scripts/ada/tools-commands-catalog.py
and shipped here by deploy-ada.sh; it is never recomputed live).

Answers "what can you do / list your tools / capabilities / what
commands / help" from backend/data/ada-tools-snapshot.json — one
mtime-keyed file read + a fixed template, no network, no model calls
(<50 ms). Canonical names only: tools[] rows whose name is an _ALIASES
key (absorbed names) are never presented as surface.

Env:
    ADA_TOOLS_SNAPSHOT — snapshot path override (tests, staging).
"""

